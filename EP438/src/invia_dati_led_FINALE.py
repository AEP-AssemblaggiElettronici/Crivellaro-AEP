def build_board_payloads(image_hsv, num_boards, strips_per_board, strip_length):
    total_strips = num_boards * strips_per_board
    matrix = []

    # Step 1: ricostruisco la matrice globale
    idx = 0
    for led_idx in range(strip_length):
        row = []
        for col in range(total_strips):
            row.append(image_hsv[idx:idx+3])
            idx += 3
        matrix.append(row)

    # Step 2: estraggo payload scheda per scheda
    board_payloads = []
    for board_id in range(num_boards):
        payload = []
        for strip_idx in range(strips_per_board):
            col = board_id*strips_per_board + strip_idx
            for led_idx in range(strip_length):
                payload.extend(matrix[led_idx][col])
        board_payloads.append(payload)

    return board_payloads


def send_packet(ser, target_id, cmd, payload=None):
    if payload is None:
        payload=[]
    chk = target_id ^ cmd
    for b in payload: chk ^= b
    packet = bytearray([STX,target_id,cmd]) + bytearray(payload) + bytearray([chk])
    ser.write(packet)
    ser.flush()
    print(f"TX → ID {target_id}, CMD {cmd:02X}, LEN={len(payload)}, CHK={chk:02X}")

